from __future__ import annotations

import json
import os
import uuid
from datetime import datetime, timezone
from pathlib import Path


def data_dir():
    override = os.environ.get("KAREEM_AI_DATA_DIR")
    root = Path(override) if override else Path(os.environ.get("LOCALAPPDATA", Path.home())) / "KareemAI"
    root.mkdir(parents=True, exist_ok=True)
    return root


def write_json(path, value):
    temp = path.with_suffix(".tmp")
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
    temp.replace(path)


def read_json(path, fallback):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return fallback


class Store:
    def __init__(self, root=None):
        self.root = root or data_dir()
        self.root.mkdir(parents=True, exist_ok=True)
        self.chats_dir = self.root / "chats"
        self.chats_dir.mkdir(exist_ok=True)

    def config(self):
        return read_json(self.root / "settings.json", {"Gemini": "", "Groq": ""})

    def save_config(self, config):
        allowed = ("Gemini", "Groq", "theme", "read_replies", "speech_voice", "stt_model")
        write_json(self.root / "settings.json", {k: config[k] for k in allowed if k in config})

    def chats(self):
        chats = [read_json(p, {}) for p in self.chats_dir.glob("*.json")]
        return sorted([c for c in chats if "id" in c and "messages" in c],
                      key=lambda c: c.get("updated", ""), reverse=True)

    def save_chat(self, chat):
        # IDs are always generated by the app, never by a model.
        uuid.UUID(chat["id"])
        chat["updated"] = datetime.now(timezone.utc).isoformat()
        write_json(self.chats_dir / (chat["id"] + ".json"), chat)

    def log(self, chat_id, message):
        with (self.root / "activity.jsonl").open("a", encoding="utf-8") as f:
            f.write(json.dumps({"at": datetime.now(timezone.utc).isoformat(),
                                "chat": chat_id, "event": message}, ensure_ascii=False) + "\n")


def new_chat():
    return {"id": str(uuid.uuid4()), "title": "New conversation", "messages": [], "runs": []}


def get_key(name):
    import keyring
    return keyring.get_password("KareemAI", name) or os.environ.get(name.upper() + "_API_KEY", "")


def set_key(name, value):
    import keyring
    if value:
        keyring.set_password("KareemAI", name, value)
    else:
        try:
            keyring.delete_password("KareemAI", name)
        except keyring.errors.PasswordDeleteError:
            pass
